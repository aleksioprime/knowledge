"""
Базовые классы исключений для приложения.
Используется для обработки бизнес-логики и ошибок.
"""


class BaseException(Exception):
    """
    Базовый класс для всех пользовательских исключений приложения.
    Используется для ошибок бизнес-логики с понятными сообщениями.
    """

    def __init__(self, message: str, *args: object) -> None:
        """
        Инициализирует исключение с сообщением об ошибке.
        """
        self.message = message
        super().__init__(message, *args)